def _build_s2t_map() -> dict:
    table = {}
    for line in _S2T_PAIRS_TEXT.splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        for token in line.split():
            if len(token) != 2:
                raise AssertionError("简繁对照表的条目必须是两个字（繁＋简），实际：%r" % token)
            trad, simp = token[0], token[1]
            if trad == simp:
                raise AssertionError("简繁对照表里出现同字映射：%s" % trad)
            if trad in table and table[trad] != simp:
                raise AssertionError("简繁对照表里 %s 有两个目标：%s／%s"
                                     % (trad, table[trad], simp))
            table[trad] = simp
    return table


S2T_MAP = _build_s2t_map()


def fold_simp(text) -> str:
    """`NFKC` ＋ 常用简繁／异体**单字**折叠：数字、括号、字母、标点一律原样。"""
    s = unicodedata.normalize("NFKC", str(text or ""))
    return "".join(S2T_MAP.get(ch, ch) for ch in s)
