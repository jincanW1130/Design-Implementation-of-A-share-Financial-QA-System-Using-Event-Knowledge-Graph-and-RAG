def _pe_gold_set():
    rows = [json.loads(l) for l in io.open(PE_PATH, encoding="utf-8") if l.strip()]
    s = set()
    for q in rows:
        s.update(q["gold_evidence_chunk_ids"])
    return s


def _cand_stats(gf, chunks, docs):
    """现场重算：候选总数 / 未被 PE 占用 / gold 文档全部落在可过滤文档集合内。"""
    sys.path.insert(0, os.path.join(ROOT, "交付物/03-代码", "检索"))
    BQ.config.NODES_CSV = os.path.join(GRAPH_DIR, "nodes.csv")
    BQ.config.EDGES_CSV = os.path.join(GRAPH_DIR, "edges.csv")
    I = BQ.Inputs()
    cands = BQ.generate_candidates(I)
    now = {int(d) for d, s in _doc_dates(gf, I.node_by_id).items() if len(s) >= 2}
    pe_gold = _pe_gold_set()
    out = collections.defaultdict(lambda: [0, 0, 0])
    for c in cands:
        k = c["candidate_kind"]
        out[k][0] += 1
        if set(c["candidate_gold_chunk_ids"]) & pe_gold:
            continue
        out[k][1] += 1
        dd = {int(I.chunks[x]["doc_id"]) for x in c["candidate_gold_chunk_ids"] if x in I.chunks}
        if dd and dd <= now:
            out[k][2] += 1
    return out


