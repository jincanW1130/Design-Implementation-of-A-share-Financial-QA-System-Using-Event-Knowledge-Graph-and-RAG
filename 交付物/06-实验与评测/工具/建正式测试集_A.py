def load_inputs():
    docs = {}
    for row in BQ.config.iter_jsonl(DOCS_PATH):
        docs[int(row["doc_id"])] = row
    chunks = {}
    chunks_by_doc = collections.defaultdict(list)
    for row in BQ.config.iter_jsonl(CHUNKS_PATH):
        cid = int(row["chunk_id"])
        chunks[cid] = row
        chunks_by_doc[int(row["doc_id"])].append(cid)
    for k in chunks_by_doc:
        chunks_by_doc[k].sort()
    with io.open(os.path.join(GRAPH_DIR, "nodes.csv"), encoding="utf-8-sig", newline="") as fh:
        nodes = list(csv.DictReader(fh))
    with io.open(os.path.join(GRAPH_DIR, "edges.csv"), encoding="utf-8-sig", newline="") as fh:
        edges = list(csv.DictReader(fh))
    node_by_id = {n["node_id"]: n for n in nodes}
    return docs, chunks, chunks_by_doc, nodes, edges, node_by_id


def graph_facts(edges, node_by_id):
    event_docs = collections.defaultdict(set)      # event -> {doc_id}
    event_chunks = collections.defaultdict(set)    # event -> {chunk_id}
    chunk_events = collections.defaultdict(set)    # chunk_id -> {event}
    event_targets = collections.defaultdict(list)  # event -> [(rel, tail, chunk, doc)]
    company_events = collections.defaultdict(list)
    company_persons = collections.defaultdict(list)
    event_companies = collections.defaultdict(list)
    for e in edges:
        rel, head, tail = e["relation"], e["head_id"], e["tail_id"]
        h, t = node_by_id.get(head), node_by_id.get(tail)
        if rel == "EVIDENCED_BY" and h and t and h["label"] == "Event" and t["label"] == "Document":
            event_docs[head].add(int(t["doc_id"]))
            continue
        if e["source_chunk_id"]:
            cid = int(e["source_chunk_id"])
            for side in (head, tail):
                if side.startswith("EVT-"):
                    event_chunks[side].add(cid)
                    chunk_events[cid].add(side)
        if rel == "PARTICIPATES_IN" and h and t and h["label"] == "Company" and t["label"] == "Event":
            company_events[head].append(tail)
            event_companies[tail].append(head)
        if rel == "HAS_EXECUTIVE":
            company_persons[head].append((tail, e["source_chunk_id"], e["source_doc_id"]))
        if rel in ("ISSUED_BY", "RELATED_TO") and head.startswith("EVT-"):
            event_targets[head].append((rel, tail, e["source_chunk_id"], e["source_doc_id"]))
    return dict(event_docs=event_docs, event_chunks=event_chunks, chunk_events=chunk_events,
                event_targets=event_targets, company_events=company_events,
                company_persons=company_persons, event_companies=event_companies, _edges=edges)


