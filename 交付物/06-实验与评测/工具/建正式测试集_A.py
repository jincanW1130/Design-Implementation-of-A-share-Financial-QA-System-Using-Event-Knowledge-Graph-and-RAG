def build_records(specs, docs, chunks, gf, node_by_id):
    """把 SPECS 渲染成待写盘的记录列表（同时抛错）。"""
    recs = []
    for spec in specs:
        gold = list(spec["gold"])
        doc_ids = sorted({int(chunks[c]["doc_id"]) for c in gold})
        win = spec["win"]
        rec = {
            "qid": spec["qid"],
            "question": spec["question"],
            "reference_answer": spec["answer"],
            "task_type": spec["cell"].split("+")[0],
            "gold_hop_depth": int(spec["cell"].split("+")[1].rstrip("跳")),
            "time_constraint": "有" if win else "无",
            "time_window": ({k: win[k] for k in TW_FIELD_ORDER} if win else None),
            "gold_evidence_doc_ids": doc_ids,
            "gold_evidence_chunk_ids": gold,
            "gold_evidence_count": len(gold),
            "gold_evidence_rule": RULE[spec["kind"]],
            "gold_verified_by": VERIFIED_BY,
            "gold_review_status": REVIEW_STATUS,
            "gold_verify_anchors": [{"chunk_id": c, "quote": q} for c, q in spec["anchors"]],
            "gold_verify_note": spec["note"],
            "source_material": [{
                "category": docs[d]["category"], "doc_id": d,
                "publish_time": docs[d]["publish_time"], "source": docs[d]["source"],
                "title": docs[d]["title"], "url": docs[d]["url"]} for d in doc_ids],
            "graph_path": [],
            "cell": spec["cell"],
            "subset": spec["subset"],
            "builder": spec["builder"],
        }
        rec["graph_path"] = render_path(spec, gf, node_by_id, chunks)
        recs.append(rec)
    return recs


def render_path(spec, gf, node_by_id, chunks):
    p = spec.get("path")
    if not p:
        return []
    kind, key = p
    out = []
    if kind == "company":
        for ev in sorted(set(gf["company_events"].get(key, []))):
            for cid in sorted(gf["event_chunks"].get(ev, set())):
                if cid in spec["gold"]:
                    out.append({"head": key, "relation": "PARTICIPATES_IN", "tail": ev,
                                "source_chunk_id": cid})
        if not out:  # 事件证据块不在 gold 内时，仍给出关系本身
            for ev in sorted(set(gf["company_events"].get(key, [])))[:1]:
                out.append({"head": key, "relation": "PARTICIPATES_IN", "tail": ev,
                            "source_chunk_id": None})
    elif kind == "persons":
        for per, cid, _doc in gf["company_persons"].get(key, []):
            if cid and int(cid) in spec["gold"]:
                out.append({"head": key, "relation": "HAS_EXECUTIVE", "tail": per,
                            "source_chunk_id": int(cid)})
        if not out:
            for per, cid, _doc in gf["company_persons"].get(key, [])[:1]:
                out.append({"head": key, "relation": "HAS_EXECUTIVE", "tail": per,
                            "source_chunk_id": int(cid) if cid else None})
    elif kind == "event":
        for comp in sorted(set(gf["event_companies"].get(key, []))):
            cid = None
            for c in sorted(gf["event_chunks"].get(key, set())):
                if c in spec["gold"] and cid is None:
                    cid = c
            out.append({"head": comp, "relation": "PARTICIPATES_IN", "tail": key,
                        "source_chunk_id": cid})
        for rel, tail, cid, _doc in gf["event_targets"].get(key, []):
            out.append({"head": key, "relation": rel, "tail": tail,
                        "source_chunk_id": int(cid) if cid else None})
    elif kind == "copath":
        for e in gf["_edges"]:
            if e["relation"] == "PARTICIPATES_IN" and e["tail_id"] == key:
                out.append({"head": e["head_id"], "relation": "PARTICIPATES_IN", "tail": key,
                            "source_chunk_id": int(e["source_chunk_id"]) if e["source_chunk_id"] else None})
    return out


def pe_overlap(recs, pe_rows):
    pe_gold = set()
    for q in pe_rows:
        pe_gold.update(q["gold_evidence_chunk_ids"])
    hits = []
    for r in recs:
        inter = sorted(set(r["gold_evidence_chunk_ids"]) & pe_gold)
        if inter:
            hits.append((r["qid"], inter))
    return hits, pe_gold


def validate(recs, docs, chunks, gf, node_by_id, pe_rows):
    errs, warns = [], []

    def err(m):
        errs.append(m)

    # 1. qid 与格子分配
    if len(recs) != 84:
        err("题数不为 84：%d" % len(recs))
    for i, r in enumerate(recs, 1):
        want = "FQ-%03d" % i
        if r["qid"] != want:
            err("qid 顺序错位：第 %d 条为 %s，应为 %s" % (i, r["qid"], want))
    cells = collections.Counter((r["cell"], r["subset"], r["time_constraint"]) for r in recs)
    expect = {("事实型+0跳", "核心", "无"): 6, ("事实型+0跳", "核心", "有"): 6,
              ("事实型+2跳", "核心", "无"): 6, ("事实型+2跳", "核心", "有"): 6,
              ("事件型+0跳", "核心", "无"): 6, ("事件型+0跳", "核心", "有"): 6,
              ("事件型+1跳", "核心", "无"): 6, ("事件型+1跳", "核心", "有"): 6,
              ("关系型+1跳", "核心", "无"): 6, ("关系型+1跳", "核心", "有"): 6,
              ("关系型+2跳", "核心", "无"): 6, ("关系型+2跳", "核心", "有"): 6,
              ("关系型+2跳", "压力", "有"): 12}
    for k, v in sorted(expect.items()):
        if cells.get(k, 0) != v:
            err("格子配额不符：%s 实得 %d，应为 %d" % (k, cells.get(k, 0), v))
    for k in cells:
        if k not in expect:
            err("出现计划外的格子：%s" % (k,))

    # 2. 字段与 gold 条数
    for r in recs:
        if list(r.keys()) != FIELD_ORDER:
            err("%s 字段序不符" % r["qid"])
        n = r["gold_evidence_count"]
        if not (GOLD_MIN <= n <= GOLD_MAX):
            err("%s gold 条数越界：%d" % (r["qid"], n))
        ids = r["gold_evidence_chunk_ids"]
        if n != len(ids) or n != len(set(ids)):
            err("%s gold_evidence_count 与去重后的块数不一致" % r["qid"])
        want_docs = sorted({int(chunks[c]["doc_id"]) for c in ids})
        if want_docs != r["gold_evidence_doc_ids"]:
            err("%s gold_evidence_doc_ids 与 chunk 的 doc_id 不一致：%s != %s"
                % (r["qid"], r["gold_evidence_doc_ids"], want_docs))
        if r["time_constraint"] == "有" and r["time_window"] is None:
            err("%s 标了有时间约束但 time_window 为空" % r["qid"])
        if r["time_constraint"] == "无" and r["time_window"] is not None:
            err("%s 标了无时间约束但 time_window 非空" % r["qid"])
        # 2a. time_window 形态与 PE 集逐字段一致（缺陷 1／缺陷 5）
        if r["time_window"] is not None:
            if list(r["time_window"].keys()) != TW_FIELD_ORDER:
                err("%s time_window 键序 %s ≠ PE 集口径 %s"
                    % (r["qid"], list(r["time_window"].keys()), TW_FIELD_ORDER))
            if r["time_window"]["basis"] != "event_time":
                err("%s time_window.basis 应为 event_time" % r["qid"])
            if r["time_window"]["cutoff"] != DATA_CUTOFF_TS:
                err("%s time_window.cutoff 应为 data_cutoff_time 的规范时间戳" % r["qid"])
            if r["time_window"]["empty_policy"] != EMPTY_POLICY:
                err("%s time_window.empty_policy 应为 %s" % (r["qid"], EMPTY_POLICY))

    # 2b. 图谱路径与跳数一致：≥1 跳的题必须给出非空 graph_path，0 跳的题为空
    for r in recs:
        if r["gold_hop_depth"] > 0 and not r["graph_path"]:
            err("%s 为 %d 跳但 graph_path 为空" % (r["qid"], r["gold_hop_depth"]))
        if r["gold_hop_depth"] == 0 and r["graph_path"]:
            err("%s 为 0 跳但 graph_path 非空" % r["qid"])
        for step in r["graph_path"]:
            if list(step.keys()) != ["head", "relation", "tail", "source_chunk_id"]:
                err("%s graph_path 条目字段不符：%s" % (r["qid"], list(step.keys())))

    # 3. 锚点逐字命中
    for r in recs:
        if not r["gold_verify_anchors"]:
            err("%s 无核验锚点" % r["qid"])
        for a in r["gold_verify_anchors"]:
            cid, quote = a["chunk_id"], a["quote"]
            if cid not in chunks:
                err("%s 锚点块不存在：%d" % (r["qid"], cid))
                continue
            if cid not in r["gold_evidence_chunk_ids"]:
                err("%s 锚点块 %d 不在 gold 内" % (r["qid"], cid))
            if norm(quote) not in norm(chunks[cid]["content"]):
                err("%s 锚点未命中：%d / %s" % (r["qid"], cid, quote[:50]))
        anchored = {a["chunk_id"] for a in r["gold_verify_anchors"]}
        if anchored != set(r["gold_evidence_chunk_ids"]):
            warns.append("%s 锚点未覆盖全部 gold 块：%s vs %s"
                         % (r["qid"], sorted(anchored), r["gold_evidence_chunk_ids"]))

    # 4. 时间窗：可过滤文档集合 + 过滤前后差集
    now_docs = {int(d) for d, s in _doc_dates(gf, node_by_id).items() if len(s) >= 2}
    win_checks = []
    for r in recs:
        if r["time_constraint"] != "有":
            continue
        lo = _dt.date.fromisoformat(r["time_window"]["lo"])
        hi = _dt.date.fromisoformat(r["time_window"]["hi"])
        if not (lo <= hi):
            err("%s 时间窗上下界颠倒" % r["qid"])
        if hi > _dt.date(2026, 9, 25):
            err("%s 时间窗上界晚于 data_cutoff_time" % r["qid"])
        if not set(r["gold_evidence_doc_ids"]) <= now_docs:
            err("%s 的 gold 文档不在可过滤文档集合内：%s" % (r["qid"], r["gold_evidence_doc_ids"]))
        det = diff_check(r, gf, node_by_id, lo, hi)
        win_checks.append(det)
        if not det["ok"]:
            err("%s 过滤前后差集验证未通过：%s" % (r["qid"], det))
    return errs, warns, cells, now_docs, win_checks


def _doc_dates(gf, node_by_id):
    out = collections.defaultdict(set)
    for ev, ds in gf["event_docs"].items():
        t = (node_by_id.get(ev, {}).get("event_time") or "").strip()
        if t:
            for d in ds:
                out[int(d)].add(t)
    return out


def diff_check(rec, gf, node_by_id, lo, hi):
    """过滤前后候选差集：口径＝gold 文档承载的事件集合。"""
    scope_docs = set(rec["gold_evidence_doc_ids"])
    pre = set()
    for d in scope_docs:
        for ev, ds in gf["event_docs"].items():
            if d in ds:
                pre.add(ev)
    dated = {}
    for ev in pre:
        t = (node_by_id.get(ev, {}).get("event_time") or "").strip()
        if t:
            try:
                dated[ev] = _dt.date.fromisoformat(t[:10])
            except ValueError:
                pass
    post = {ev for ev, dt in dated.items() if lo <= dt <= hi}
    dropped = pre - post
    gold_evs = set()
    for c in rec["gold_evidence_chunk_ids"]:
        gold_evs |= gf["chunk_events"].get(c, set())
    return {"qid": rec["qid"], "docs": sorted(scope_docs), "pre": len(pre), "post": len(post),
            "drop": len(dropped), "post_dates": sorted(d.isoformat() for d in
                                                       {dated[e] for e in post}),
            "drop_dates": sorted(d.isoformat() for d in
                                 {dated[e] for e in dropped if e in dated}),
            "gold_in_window": bool(gold_evs & post) if gold_evs else None,
            "ok": bool(post) and bool(dropped) and (bool(gold_evs & post) if gold_evs else True)}


def write_jsonl(path, recs):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with io.open(path, "w", encoding="utf-8", newline="\n") as fh:
        for r in recs:
            fh.write(json.dumps(r, ensure_ascii=False, separators=(", ", ": ")))
            fh.write("\n")


